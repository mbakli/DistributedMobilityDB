----------------------------------------------------------------------------------------------------------------------
--Q1) Identify the hottest areas in the past 24 hours
----------------------------------------------------------------------------------------------------------------------
SELECT station, loc
FROM GSOD_TEMP
WHERE temp_tfloat && tstzspan '[2024-01-01, 2024-01-01]'
	AND temp_tfloat ?> 95 -- Fahrenheit
----------------------------------------------------------------------------------------------------------------------
--Q2) Retrieve weather data for a specific location over time
----------------------------------------------------------------------------------------------------------------------
SELECT station, temp_tfloat
FROM GSOD_TEMP
WHERE ST_Within(loc, ST_SetSRID(ST_MakePoint(-5.6833333, 11.35), 4326))
----------------------------------------------------------------------------------------------------------------------
--Q3) Retrieve the average temperature for each location over a specific period
----------------------------------------------------------------------------------------------------------------------
SELECT loc, twavg(temp_tfloat)
FROM GSOD_TEMP
WHERE temp_tfloat && tstzspan '[2024-01-01, 2024-01-31]'
----------------------------------------------------------------------------------------------------------------------
--Q4) Retrieve the maximum temperature for each location
----------------------------------------------------------------------------------------------------------------------
SELECT loc, xmax(extent(temp_tfloat))
FROM GSOD_TEMP
GROUP BY loc;
----------------------------------------------------------------------------------------------------------------------
--Q5) Count the number of days with precipitation above a certain threshold for each station.
----------------------------------------------------------------------------------------------------------------------
SELECT station, COUNT(*) AS rainy_days
FROM GSOD_TEMP
WHERE precipitation_tfloat ?> 10
GROUP BY station;
